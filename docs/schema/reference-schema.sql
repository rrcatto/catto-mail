-- =============================================================================
-- Smarthost reference schema — specification 2.3 (PostgreSQL 16; unchanged since 2.1)
-- =============================================================================
--
-- THIS IS NOT A MIGRATION. Symfony/Doctrine migrations (Phase 2) are the sole
-- authority for schema objects (tables, indexes, foreign keys, constraints).
-- PostgreSQL roles and grants are infrastructure (infra/ bootstrap, D-15) and
-- are deliberately absent here. This file is the normative reference that the
-- Doctrine entities, the Python validator and the Go delivery daemon are built
-- against; Phase 2 migrations must reproduce it. Never apply it to a real
-- database.
--
-- Conventions (docs/architecture/conventions.md):
--   * ids: uuid, UUIDv7 generated by the writing application (no DB default).
--   * timestamps: timestamptz, UTC.
--   * enums: text + CHECK, values from docs/contracts/status-vocabulary.yaml.
--   * JSON: jsonb.
--   * Foreign keys: NO ACTION on delete (history is never cascaded away).
--   * Address normalisation (D-18): trim surrounding whitespace, preserve the
--     local part exactly, lower-case the domain. Performed by the application;
--     CHECKs below only verify the domain is lower-case.
--   * Leased work (D-03): claimed_by, lease_expires_at, attempt_count,
--     next_attempt_at, last_error.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Tenancy, people, domains and authentication
-- -----------------------------------------------------------------------------

CREATE TABLE clients (
    id             uuid        PRIMARY KEY,
    company_name   text        NOT NULL,
    contact_email  text        NOT NULL,
    status         text        NOT NULL DEFAULT 'pending_approval'
        CHECK (status IN ('pending_approval', 'active', 'throttled', 'suspended', 'closed')),
    plan           text        NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- Dashboard login accounts (D-12). API keys are never browser credentials.
CREATE TABLE users (
    id             uuid        PRIMARY KEY,
    email          text        NOT NULL,                             -- login identifier
    password_hash  text        NULL,                                 -- Symfony PasswordHasher output; NULL = invited, cannot log in yet
    display_name   text        NULL,
    global_role    text        NULL CHECK (global_role IN ('operator')),   -- NULL = no global role
    status         text        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at     timestamptz NOT NULL DEFAULT now(),
    last_login_at  timestamptz NULL,
    disabled_at    timestamptz NULL
);
-- Login identity rule: unique case-insensitively. Never reused as the SMTP
-- mailbox-normalisation rule (D-18).
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));

CREATE TABLE client_memberships (
    id          uuid        PRIMARY KEY,
    user_id     uuid        NOT NULL REFERENCES users (id),
    client_id   uuid        NOT NULL REFERENCES clients (id),
    role        text        NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX client_memberships_user_client_uq ON client_memberships (user_id, client_id);
CREATE INDEX client_memberships_client_idx ON client_memberships (client_id);

-- Sending domains with DNS TXT verification and DKIM status (D-13, D-26).
-- TXT record: _smarthost-verification.<domain>  "smarthost-verification=<token>".
-- The token is published in DNS, is not an authentication secret and is stored as-is.
CREATE TABLE sending_domains (
    id                  uuid        PRIMARY KEY,
    client_id           uuid        NOT NULL REFERENCES clients (id),
    domain              text        NOT NULL CHECK (domain = lower(domain) AND position('@' IN domain) = 0),
    status              text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'disabled')),
    verification_token  text        NOT NULL CHECK (verification_token ~ '^[A-Za-z0-9_-]{22,}$'),  -- >= 128 bits base64url
    verified_at         timestamptz NULL,
    last_checked_at     timestamptz NULL,
    last_check_error    text        NULL,
    dkim_selector       text        NULL,
    dkim_status         text        NOT NULL DEFAULT 'not_configured'
        CHECK (dkim_status IN ('not_configured', 'pending_dns', 'active', 'disabled')),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT sending_domains_verified_has_time CHECK (status <> 'verified' OR verified_at IS NOT NULL),
    CONSTRAINT sending_domains_dkim_has_selector CHECK (dkim_status = 'not_configured' OR dkim_selector IS NOT NULL)
);
CREATE UNIQUE INDEX sending_domains_client_domain_uq ON sending_domains (client_id, domain);
CREATE INDEX sending_domains_domain_idx ON sending_domains (domain);

CREATE TABLE api_keys (
    id            uuid        PRIMARY KEY,
    client_id     uuid        NOT NULL REFERENCES clients (id),
    key_hash      text        NOT NULL CHECK (key_hash ~ '^[0-9a-f]{64}$'),  -- SHA-256 hex
    key_prefix    text        NOT NULL,                                       -- non-secret display prefix
    name          text        NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_used_at  timestamptz NULL,
    revoked_at    timestamptz NULL
);
CREATE UNIQUE INDEX api_keys_key_hash_uq ON api_keys (key_hash);
CREATE INDEX api_keys_client_id_idx ON api_keys (client_id);

-- -----------------------------------------------------------------------------
-- Validation
-- -----------------------------------------------------------------------------

CREATE TABLE validation_jobs (
    id                          uuid        PRIMARY KEY,
    client_id                   uuid        NOT NULL REFERENCES clients (id),
    external_reference          text        NULL,
    idempotency_key             text        NOT NULL,
    request_hash                text        NOT NULL,                -- detects key reuse with a different body
    status                      text        NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'processing', 'completed', 'failed', 'cancelled')),
    submitted_at                timestamptz NOT NULL DEFAULT now(),
    started_at                  timestamptz NULL,
    completed_at                timestamptz NULL,
    total_addresses             integer     NOT NULL CHECK (total_addresses BETWEEN 1 AND 10000),
    processed_count             integer     NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    classification_counts_json  jsonb       NOT NULL DEFAULT '{}'::jsonb
);
CREATE UNIQUE INDEX validation_jobs_client_idempotency_uq ON validation_jobs (client_id, idempotency_key);
CREATE INDEX validation_jobs_client_status_idx ON validation_jobs (client_id, status);
CREATE INDEX validation_jobs_client_external_ref_idx ON validation_jobs (client_id, external_reference)
    WHERE external_reference IS NOT NULL;

CREATE TABLE validation_addresses (
    id                          uuid        PRIMARY KEY,
    job_id                      uuid        NOT NULL REFERENCES validation_jobs (id),
    external_address_reference  text        NULL,                    -- D-21: opaque client reference per address
    original_address            text        NOT NULL,                -- verbatim input, never modified
    normalized_address          text        NULL,
    syntax_status               text        NULL CHECK (syntax_status IN ('valid', 'invalid')),
    domain_status               text        NULL CHECK (domain_status IN (
        'mx', 'null_mx', 'address_fallback', 'no_mail_host', 'nxdomain',
        'temporary_failure', 'invalid_response', 'skipped')),
    smtp_status                 text        NULL CHECK (smtp_status IN (
        'accepted', 'rejected', 'temporary_failure', 'blocked', 'timeout',
        'connection_failed', 'inconclusive', 'skipped')),
    is_role                     boolean     NULL,
    is_disposable               boolean     NULL,
    is_catch_all_or_accept_all  boolean     NULL,
    is_domain_typo_suspected    boolean     NULL,
    suggested_address           text        NULL,                    -- suggestion only (D-04)
    suggestion_reason_code      text        NULL CHECK (suggestion_reason_code IN (
        'provider_domain_edit_distance', 'transposition', 'tld_typo',
        'legacy_domain_alias', 'other_domain_typo_rule')),
    suggestion_confidence       text        NULL CHECK (suggestion_confidence IN ('low', 'medium', 'high')),
    overall_classification      text        NULL CHECK (overall_classification IN (
        'deliverable', 'probably_deliverable', 'undeliverable',
        'temporarily_unverifiable', 'unknown', 'risky')),
    confidence                  text        NULL CHECK (confidence IN ('low', 'medium', 'high')),
    diagnostic_code             text        NULL,
    diagnostic_text             text        NULL,
    checked_at                  timestamptz NULL,
    -- Leased work (validator only; not exposed by the API)
    processing_state            text        NOT NULL DEFAULT 'pending'
        CHECK (processing_state IN ('pending', 'claimed', 'retry_scheduled', 'done')),
    claimed_by                  text        NULL,
    lease_expires_at            timestamptz NULL,
    attempt_count               integer     NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at             timestamptz NULL,
    last_error                  text        NULL,
    CONSTRAINT validation_addresses_done_has_result CHECK (
        processing_state <> 'done' OR (overall_classification IS NOT NULL AND checked_at IS NOT NULL)),
    CONSTRAINT validation_addresses_claim_has_lease CHECK (
        processing_state <> 'claimed' OR (claimed_by IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CONSTRAINT validation_addresses_suggestion_complete CHECK (
        (suggested_address IS NULL) = (suggestion_reason_code IS NULL)
        AND (suggested_address IS NULL) = (suggestion_confidence IS NULL))
);
CREATE INDEX validation_addresses_job_id_idx ON validation_addresses (job_id, id);
CREATE INDEX validation_addresses_normalized_address_idx ON validation_addresses (normalized_address);
CREATE INDEX validation_addresses_claimable_idx ON validation_addresses (processing_state, next_attempt_at, lease_expires_at)
    WHERE processing_state <> 'done';

CREATE TABLE validation_evidence (
    id                     uuid        PRIMARY KEY,
    validation_address_id  uuid        NOT NULL REFERENCES validation_addresses (id),
    evidence_type          text        NOT NULL CHECK (evidence_type IN (
        'dns_mx', 'dns_address', 'smtp_connect', 'smtp_ehlo', 'smtp_mail_from',
        'smtp_rcpt_to', 'smtp_accept_all_probe')),
    provider_host          text        NULL,
    response_code          smallint    NULL,
    enhanced_status_code   text        NULL,
    detail_json            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    occurred_at            timestamptz NOT NULL
);
CREATE INDEX validation_evidence_address_occurred_idx ON validation_evidence (validation_address_id, occurred_at);

CREATE TABLE disposable_domains (
    domain            text        PRIMARY KEY CHECK (domain = lower(domain)),
    source            text        NOT NULL,
    added_at          timestamptz NOT NULL DEFAULT now(),
    last_verified_at  timestamptz NULL
);

