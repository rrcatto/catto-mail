-- =============================================================================
-- Smarthost reference schema — specification 2.10 (PostgreSQL 16; D-30 in 2.4, D-38 in 2.5, engagement index in 2.6, access control in 2.7,
-- webhooks in 2.8, delivery heartbeats in 2.9, client lifecycle, limits, quotas, billing boundary and reputation in 2.10)
-- =============================================================================
--
-- THIS IS NOT A MIGRATION. Symfony/Doctrine migrations (Phase 2) are the sole
-- authority for schema objects (tables, indexes, foreign keys, constraints).
-- PostgreSQL roles and grants are infrastructure (infra/ bootstrap, D-15) and
-- are deliberately absent here. This file is the normative reference that the
-- Doctrine entities, the Python validator and the Go delivery daemon are built
-- against; Phase 2 migrations must reproduce it. Never apply it to a real
-- database.
--
-- Conventions (docs/architecture/conventions.md):
--   * ids: uuid, UUIDv7 generated by the writing application (no DB default).
--   * timestamps: timestamptz, UTC.
--   * enums: text + CHECK, values from docs/contracts/status-vocabulary.yaml.
--   * JSON: jsonb.
--   * Foreign keys: NO ACTION on delete (history is never cascaded away).
--   * Address normalisation (D-18): trim surrounding whitespace, preserve the
--     local part exactly, lower-case the domain. Performed by the application;
--     CHECKs below only verify the domain is lower-case.
--   * Leased work (D-03): claimed_by, lease_expires_at, attempt_count,
--     next_attempt_at, last_error.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Tenancy, people, domains and authentication
-- -----------------------------------------------------------------------------

CREATE TABLE clients (
    id             uuid        PRIMARY KEY,
    company_name   text        NOT NULL,
    contact_email  text        NOT NULL,
    status         text        NOT NULL DEFAULT 'pending_approval'
        CHECK (status IN ('pending_approval', 'active', 'throttled', 'suspended', 'closed')),
    plan           text        NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    -- D-30: operator-granted capability to report recipient global opt-outs. Never set by the client.
    can_submit_global_suppressions  boolean  NOT NULL DEFAULT false,
    -- Specification 2.10 (Phase 9): account lifecycle and operational metadata.
    -- How the client record came to exist; public_application requires APP_PUBLIC_ONBOARDING_ENABLED.
    origin                      text        NOT NULL DEFAULT 'operator' CHECK (origin IN ('operator', 'public_application')),
    billing_contact_email       text        NULL,                -- when distinct from contact_email
    abuse_contact_email         text        NULL,                -- abuse/security contact
    status_changed_at           timestamptz NOT NULL DEFAULT now(),
    approved_at                 timestamptz NULL,                -- first transition to active
    closed_at                   timestamptz NULL,
    -- Whether approval needs an acceptance of the policy version in force (APP_ACCEPTABLE_USE_POLICY_VERSION).
    -- Operator-created internal clients may be exempt explicitly.
    policy_acceptance_required  boolean     NOT NULL DEFAULT true,
    CONSTRAINT clients_closed_has_time CHECK (status <> 'closed' OR closed_at IS NOT NULL)
);
CREATE INDEX clients_status_changed_idx ON clients (status, status_changed_at);   -- approval queue, status filter


-- Dashboard accounts (D-12). Passwordless: sign-in is by single-use emailed link
-- (auth_login_tokens). API keys are never browser credentials. Installation-wide
-- roles are in user_roles; client access is in client_memberships.
CREATE TABLE users (
    id             uuid        PRIMARY KEY,
    email          text        NOT NULL,                             -- login identifier
    display_name   text        NULL,
    status         text        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at     timestamptz NOT NULL DEFAULT now(),
    last_login_at  timestamptz NULL,
    disabled_at    timestamptz NULL
);
-- Login identity rule: unique case-insensitively. Never reused as the SMTP
-- mailbox-normalisation rule (D-18).
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));

CREATE TABLE client_memberships (
    id          uuid        PRIMARY KEY,
    user_id     uuid        NOT NULL REFERENCES users (id),
    client_id   uuid        NOT NULL REFERENCES clients (id),
    role        text        NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX client_memberships_user_client_uq ON client_memberships (user_id, client_id);
CREATE INDEX client_memberships_client_idx ON client_memberships (client_id);

-- Installation-wide roles and the permission keys they grant (App\Access\PermissionCatalog;
-- keys are code, not rows). Built-in: ADMIN (every permission by definition, no rows) and
-- OPERATOR (seeded with every PLATFORM.* permission, editable). Specification 2.7.
CREATE TABLE roles (
    id           uuid        PRIMARY KEY,
    role_key     text        NOT NULL CHECK (role_key ~ '^[A-Z][A-Z0-9_]{1,63}$'),
    name         text        NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    description  text        NOT NULL DEFAULT '',
    is_builtin   boolean     NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX roles_key_uq ON roles (role_key);

CREATE TABLE role_permissions (
    id              uuid        PRIMARY KEY,
    role_id         uuid        NOT NULL REFERENCES roles (id),
    permission_key  text        NOT NULL CHECK (permission_key ~ '^[A-Z][A-Z_]*(\.[A-Z][A-Z_]*)+$'),
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX role_permissions_role_permission_uq ON role_permissions (role_id, permission_key);

CREATE TABLE user_roles (
    id           uuid        PRIMARY KEY,
    user_id      uuid        NOT NULL REFERENCES users (id),
    role_id      uuid        NOT NULL REFERENCES roles (id),
    assigned_by  uuid        NULL REFERENCES users (id),
    assigned_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_roles_user_role_uq ON user_roles (user_id, role_id);
CREATE INDEX user_roles_role_idx ON user_roles (role_id);

-- Single-use emailed sign-in links. Only the SHA-256 of the token is stored; the
-- rows double as the request history for the per-address and per-IP rate limits
-- (the IP is stored only as a keyed hash). user_id is NULL when the link was
-- issued to APP_ADMIN_EMAIL before that account existed.
CREATE TABLE auth_login_tokens (
    id                 uuid        PRIMARY KEY,
    email              text        NOT NULL,
    user_id            uuid        NULL REFERENCES users (id),
    token_hash         text        NOT NULL CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    return_path        text        NULL CHECK (return_path IS NULL OR return_path ~ '^/dashboard(/[^/]|$)'),
    requested_ip_hash  text        NOT NULL CHECK (requested_ip_hash ~ '^[0-9a-f]{64}$'),
    created_at         timestamptz NOT NULL DEFAULT now(),
    expires_at         timestamptz NOT NULL,
    used_at            timestamptz NULL,
    CONSTRAINT auth_login_tokens_expiry_after_creation CHECK (expires_at > created_at)
);
CREATE UNIQUE INDEX auth_login_tokens_hash_uq ON auth_login_tokens (token_hash);
CREATE INDEX auth_login_tokens_email_created_idx ON auth_login_tokens (lower(email), created_at);
CREATE INDEX auth_login_tokens_ip_created_idx ON auth_login_tokens (requested_ip_hash, created_at);
CREATE INDEX auth_login_tokens_user_idx ON auth_login_tokens (user_id) WHERE user_id IS NOT NULL;

-- Sending domains with DNS TXT verification and DKIM status (D-13, D-26).
-- TXT record: _smarthost-verification.<domain>  "smarthost-verification=<token>".
-- The token is published in DNS, is not an authentication secret and is stored as-is.
CREATE TABLE sending_domains (
    id                  uuid        PRIMARY KEY,
    client_id           uuid        NOT NULL REFERENCES clients (id),
    domain              text        NOT NULL CHECK (domain = lower(domain) AND position('@' IN domain) = 0),
    status              text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'disabled')),
    verification_token  text        NOT NULL CHECK (verification_token ~ '^[A-Za-z0-9_-]{22,}$'),  -- >= 128 bits base64url
    verified_at         timestamptz NULL,
    last_checked_at     timestamptz NULL,
    last_check_error    text        NULL,
    dkim_selector       text        NULL,
    dkim_status         text        NOT NULL DEFAULT 'not_configured'
        CHECK (dkim_status IN ('not_configured', 'pending_dns', 'active', 'disabled')),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT sending_domains_verified_has_time CHECK (status <> 'verified' OR verified_at IS NOT NULL),
    CONSTRAINT sending_domains_dkim_has_selector CHECK (dkim_status = 'not_configured' OR dkim_selector IS NOT NULL)
);
CREATE UNIQUE INDEX sending_domains_client_domain_uq ON sending_domains (client_id, domain);
CREATE INDEX sending_domains_domain_idx ON sending_domains (domain);

CREATE TABLE api_keys (
    id            uuid        PRIMARY KEY,
    client_id     uuid        NOT NULL REFERENCES clients (id),
    key_hash      text        NOT NULL CHECK (key_hash ~ '^[0-9a-f]{64}$'),  -- SHA-256 hex
    key_prefix    text        NOT NULL,                                       -- non-secret display prefix
    name          text        NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_used_at  timestamptz NULL,
    revoked_at    timestamptz NULL,
    expires_at    timestamptz NULL,                                           -- Phase 9: optional expiry; NULL = none
    CONSTRAINT api_keys_expiry_after_creation CHECK (expires_at IS NULL OR expires_at > created_at)
);
CREATE UNIQUE INDEX api_keys_key_hash_uq ON api_keys (key_hash);
CREATE INDEX api_keys_client_id_idx ON api_keys (client_id);

-- Per-client operational limits (Phase 9). One optional row per client; NULL means
-- "no client-specific limit": the installation ceiling (where one exists) applies. A
-- client limit may lower an installation ceiling, never raise it (enforced by the
-- application, which uses min(client limit, ceiling)).
CREATE TABLE client_limits (
    client_id                     uuid        PRIMARY KEY REFERENCES clients (id),
    api_requests_per_minute       integer     NULL CHECK (api_requests_per_minute >= 1),
    validation_jobs_per_day       integer     NULL CHECK (validation_jobs_per_day >= 0),
    validation_addresses_per_day  bigint      NULL CHECK (validation_addresses_per_day >= 0),
    validation_addresses_per_month bigint     NULL CHECK (validation_addresses_per_month >= 0),
    send_jobs_per_day             integer     NULL CHECK (send_jobs_per_day >= 0),
    send_recipients_per_day       bigint      NULL CHECK (send_recipients_per_day >= 0),
    send_recipients_per_month     bigint      NULL CHECK (send_recipients_per_month >= 0),
    max_recipients_per_send_job   integer     NULL CHECK (max_recipients_per_send_job BETWEEN 1 AND 10000),
    max_api_keys                  integer     NULL CHECK (max_api_keys >= 0),
    max_webhook_endpoints         integer     NULL CHECK (max_webhook_endpoints >= 0),
    max_sending_domains           integer     NULL CHECK (max_sending_domains >= 0),
    updated_at                    timestamptz NOT NULL DEFAULT now()
);

-- Admitted-work counters per client, metric and UTC period (Phase 9 quotas). Incremented
-- in the transaction that admits the work (INSERT ... ON CONFLICT DO UPDATE ... RETURNING),
-- so concurrent requests serialise on the row and a rolled-back request leaves no count.
-- Derived data: reconcilable against validation_jobs, send_jobs and send_job_recipient_batches.
CREATE TABLE client_quota_usage (
    client_id     uuid        NOT NULL REFERENCES clients (id),
    metric        text        NOT NULL CHECK (metric IN ('validation_jobs', 'validation_addresses', 'send_jobs', 'send_recipients')),
    period        text        NOT NULL CHECK (period IN ('day', 'month')),
    period_start  date        NOT NULL,                          -- UTC calendar day or first day of the UTC month
    used          bigint      NOT NULL CHECK (used >= 0),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (client_id, metric, period, period_start),
    CONSTRAINT client_quota_usage_month_start CHECK (period <> 'month' OR extract(day FROM period_start) = 1)
);

-- Private operator notes about a client account (Phase 9). Never shown to the client.
CREATE TABLE client_notes (
    id              uuid        PRIMARY KEY,
    client_id       uuid        NOT NULL REFERENCES clients (id),
    author_user_id  uuid        NULL REFERENCES users (id),      -- NULL for console/system notes
    note            text        NOT NULL CHECK (length(note) BETWEEN 1 AND 4000),
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX client_notes_client_created_idx ON client_notes (client_id, created_at);

-- Acceptances of the service policy (acceptable use) by version (Phase 9). Append-only and
-- content-neutral: the policy text lives outside the application; only its version is recorded.
CREATE TABLE client_policy_acceptances (
    id                   uuid        PRIMARY KEY,
    client_id            uuid        NOT NULL REFERENCES clients (id),
    policy_version       text        NOT NULL CHECK (policy_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$'),
    accepted_at          timestamptz NOT NULL DEFAULT now(),
    accepted_by_user_id  uuid        NULL REFERENCES users (id),
    source               text        NOT NULL CHECK (source IN ('client_dashboard', 'operator_recorded')),
    reference            text        NULL CHECK (length(reference) <= 255)   -- e.g. a signed agreement's reference
);
CREATE UNIQUE INDEX client_policy_acceptances_client_version_uq ON client_policy_acceptances (client_id, policy_version);

-- -----------------------------------------------------------------------------
-- Validation
-- -----------------------------------------------------------------------------

CREATE TABLE validation_jobs (
    id                          uuid        PRIMARY KEY,
    client_id                   uuid        NOT NULL REFERENCES clients (id),
    external_reference          text        NULL,
    idempotency_key             text        NOT NULL,
    request_hash                text        NOT NULL,                -- detects key reuse with a different body
    status                      text        NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'processing', 'completed', 'failed', 'cancelled')),
    submitted_at                timestamptz NOT NULL DEFAULT now(),
    started_at                  timestamptz NULL,
    completed_at                timestamptz NULL,
    total_addresses             integer     NOT NULL CHECK (total_addresses BETWEEN 1 AND 10000),
    processed_count             integer     NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    classification_counts_json  jsonb       NOT NULL DEFAULT '{}'::jsonb
);
CREATE UNIQUE INDEX validation_jobs_client_idempotency_uq ON validation_jobs (client_id, idempotency_key);
CREATE INDEX validation_jobs_client_status_idx ON validation_jobs (client_id, status);
CREATE INDEX validation_jobs_client_external_ref_idx ON validation_jobs (client_id, external_reference)
    WHERE external_reference IS NOT NULL;

CREATE TABLE validation_addresses (
    id                          uuid        PRIMARY KEY,
    job_id                      uuid        NOT NULL REFERENCES validation_jobs (id),
    external_address_reference  text        NULL,                    -- D-21: opaque client reference per address
    original_address            text        NOT NULL,                -- verbatim input, never modified
    normalized_address          text        NULL,
    syntax_status               text        NULL CHECK (syntax_status IN ('valid', 'invalid')),
    domain_status               text        NULL CHECK (domain_status IN (
        'mx', 'null_mx', 'address_fallback', 'no_mail_host', 'nxdomain',
        'temporary_failure', 'invalid_response', 'skipped')),
    smtp_status                 text        NULL CHECK (smtp_status IN (
        'accepted', 'rejected', 'temporary_failure', 'blocked', 'timeout',
        'connection_failed', 'inconclusive', 'skipped')),
    is_role                     boolean     NULL,
    is_disposable               boolean     NULL,
    is_catch_all_or_accept_all  boolean     NULL,
    is_domain_typo_suspected    boolean     NULL,
    suggested_address           text        NULL,                    -- suggestion only (D-04)
    suggestion_reason_code      text        NULL CHECK (suggestion_reason_code IN (
        'provider_domain_edit_distance', 'transposition', 'tld_typo',
        'legacy_domain_alias', 'other_domain_typo_rule')),
    suggestion_confidence       text        NULL CHECK (suggestion_confidence IN ('low', 'medium', 'high')),
    overall_classification      text        NULL CHECK (overall_classification IN (
        'deliverable', 'probably_deliverable', 'undeliverable',
        'temporarily_unverifiable', 'unknown', 'risky')),
    confidence                  text        NULL CHECK (confidence IN ('low', 'medium', 'high')),
    diagnostic_code             text        NULL,
    diagnostic_text             text        NULL,
    checked_at                  timestamptz NULL,
    -- Leased work (validator only; not exposed by the API)
    processing_state            text        NOT NULL DEFAULT 'pending'
        CHECK (processing_state IN ('pending', 'claimed', 'retry_scheduled', 'done')),
    claimed_by                  text        NULL,
    lease_expires_at            timestamptz NULL,
    attempt_count               integer     NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at             timestamptz NULL,
    last_error                  text        NULL,
    CONSTRAINT validation_addresses_done_has_result CHECK (
        processing_state <> 'done' OR (overall_classification IS NOT NULL AND checked_at IS NOT NULL)),
    CONSTRAINT validation_addresses_claim_has_lease CHECK (
        processing_state <> 'claimed' OR (claimed_by IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CONSTRAINT validation_addresses_suggestion_complete CHECK (
        (suggested_address IS NULL) = (suggestion_reason_code IS NULL)
        AND (suggested_address IS NULL) = (suggestion_confidence IS NULL))
);
CREATE INDEX validation_addresses_job_id_idx ON validation_addresses (job_id, id);
CREATE INDEX validation_addresses_normalized_address_idx ON validation_addresses (normalized_address);
CREATE INDEX validation_addresses_claimable_idx ON validation_addresses (processing_state, next_attempt_at, lease_expires_at)
    WHERE processing_state <> 'done';

CREATE TABLE validation_evidence (
    id                     uuid        PRIMARY KEY,
    validation_address_id  uuid        NOT NULL REFERENCES validation_addresses (id),
    evidence_type          text        NOT NULL CHECK (evidence_type IN (
        'dns_mx', 'dns_address', 'smtp_connect', 'smtp_ehlo', 'smtp_mail_from',
        'smtp_rcpt_to', 'smtp_accept_all_probe')),
    provider_host          text        NULL,
    response_code          smallint    NULL,
    enhanced_status_code   text        NULL,
    detail_json            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    occurred_at            timestamptz NOT NULL
);
CREATE INDEX validation_evidence_address_occurred_idx ON validation_evidence (validation_address_id, occurred_at);

CREATE TABLE disposable_domains (
    domain            text        PRIMARY KEY CHECK (domain = lower(domain)),
    source            text        NOT NULL,
    added_at          timestamptz NOT NULL DEFAULT now(),
    last_verified_at  timestamptz NULL
);

